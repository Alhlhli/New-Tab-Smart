    function fmtAudioTime(sec) {
      if (!Number.isFinite(sec) || sec < 0) return '0:00';
      const total = Math.floor(sec);
      const h = Math.floor(total / 3600);
      const m = Math.floor((total % 3600) / 60);
      const ss = pad2(total % 60);
      return h ? `${h}:${pad2(m)}:${ss}` : `${m}:${ss}`;
    }

