    function startLayoutPointer(event, widget, mode) {
      if (!layoutEditing || !layoutData || !widget) return;
      if (event.pointerType === 'mouse' && event.button !== 0) return;

      const rect = layoutData.widgets[widget.id];
      const dash = layoutDashboard();
      if (!rect || !dash) return;

      layoutDrag = {
        id: widget.id,
        mode,
        pointerId: event.pointerId,
        startX: event.clientX,
        startY: event.clientY,
        rect: { ...rect },
        width: dash.clientWidth || 1,
        moved: false
      };

      widget.classList.add('layout-active');
      try { event.currentTarget.setPointerCapture(event.pointerId); } catch (e) { /* ignore */ }
      document.body.style.cursor = mode === 'move' ? 'move' : 'nwse-resize';
      event.preventDefault();
      event.stopPropagation();
    }

    function onLayoutPointerMove(event) {
      if (!layoutDrag || !layoutData) return;
      if (event.pointerId !== layoutDrag.pointerId) return;

      const dash = layoutDashboard();
      if (!dash) return;

      const width = dash.clientWidth || layoutDrag.width;
      const dx = (event.clientX - layoutDrag.startX) / width;
      const dy = (event.clientY - layoutDrag.startY) / width;

      if (Math.abs(dx) > 0.0005 || Math.abs(dy) > 0.0005) layoutDrag.moved = true;

      let next;
      if (layoutDrag.mode === 'move') {
        next = {
          x: Math.max(0, Math.min(1 - layoutDrag.rect.w, layoutDrag.rect.x + dx)),
          y: Math.max(0, layoutDrag.rect.y + dy),
          w: layoutDrag.rect.w,
          h: layoutDrag.rect.h
        };
      } else {
        const minWidth = Math.min(layoutDrag.rect.w, LAYOUT_MIN_CARD_WIDTH / width);
        const minHeight = Math.min(layoutDrag.rect.h, LAYOUT_MIN_CARD_HEIGHT / width);

        let newWidth = layoutDrag.rect.w - dx;
        let newX = layoutDrag.rect.x + dx;

        if (newWidth < minWidth) {
          newWidth = minWidth;
          newX = layoutDrag.rect.x + layoutDrag.rect.w - minWidth;
        }
        if (newX < 0) {
          newX = 0;
          newWidth = layoutDrag.rect.x + layoutDrag.rect.w;
        }
        newWidth = Math.min(newWidth, 1 - newX);

        next = {
          x: newX,
          y: layoutDrag.rect.y,
          w: Math.max(minWidth, newWidth),
          h: Math.max(minHeight, layoutDrag.rect.h + dy)
        };
      }

      layoutData.widgets[layoutDrag.id] = next;
      applyLayoutGeometry();
      event.preventDefault();
    }

    function endLayoutPointer(event) {
      if (!layoutDrag) return;
      if (event && event.pointerId !== undefined && event.pointerId !== layoutDrag.pointerId) return;

      const finished = layoutDrag;
      layoutDrag = null;
      document.body.style.cursor = '';

      const widget = $(finished.id);
      if (widget) widget.classList.remove('layout-active');

      if (finished.moved && layoutData && layoutData.widgets[finished.id]) {
        const current = layoutData.widgets[finished.id];
        layoutData.base[finished.id] = { ...current };
        layoutData.scale[finished.id] = 100;
        saveLayoutData();
        refreshScaleControl(finished.id);
      }
    }

