    // --- خريطة الاسم→رقم السورة (تطبيع يوحّد الهمزات والتشكيل والتاء المربوطة) ---
    function normalizeSurahName(value) {
      return String(value || '')
        .replace(/[\u064B-\u065F\u0670\u0640]/g, '') // التشكيل والتطويل
        .replace(/سور[هة]/g, '')                     // كلمة «سورة»
        .replace(/[أإآٱ]/g, 'ا')
        .replace(/[ؤئء]/g, '')
        .replace(/ة/g, 'ه')
        .replace(/ى/g, 'ي')
        .replace(/\s+/g, ' ')
        .trim();
    }

    const SURAH_NAME_MAP = {};
    SURAH_DATA.forEach((row, index) => {
      SURAH_NAME_MAP[normalizeSurahName(row[0])] = index + 1;
    });
    SURAH_NAME_MAP[normalizeSurahName('الانشراح')] = 94; // اسم بديل لسورة الشرح

    function lookupSurahNumber(text) {
      const key = normalizeSurahName(text);
      if (!key) return null;
      if (SURAH_NAME_MAP[key]) return SURAH_NAME_MAP[key];
      // بحث مرن بالتضمين للنصوص الأطول من 3 أحرف (يتجاهل الأسماء القصيرة مثل «ص» و«ق»)
      if (key.length >= 3) {
        for (const name in SURAH_NAME_MAP) {
          if (name.length >= 3 && (name.includes(key) || key.includes(name))) {
            return SURAH_NAME_MAP[name];
          }
        }
      }
      return null;
    }

    // تحويل سطر المصدر مثل «سورة الفرقان : 58» أو «سورة الطلاق : 2-3» إلى أرقام قابلة للتشغيل
    function parseAyahSourceRef(raw) {
      const text = String(raw || '');
      const splitIdx = text.lastIndexOf(':');
      if (splitIdx === -1) return null;
      const surahNum = lookupSurahNumber(text.slice(0, splitIdx));
      if (!surahNum) return null;
      const maxAyah = SURAH_DATA[surahNum - 1][2];
      const numbers = (text.slice(splitIdx + 1).match(/\d+/g) || [])
        .map(Number)
        .filter((n) => n >= 1 && n <= maxAyah);
      if (!numbers.length) return null;
      const start = numbers[0];
      const end = numbers.length > 1 ? Math.max(start, Math.min(numbers[1], maxAyah)) : start;
      return { surahNum, start, end };
    }

    const AYAH_AUDIO_BASE = 'https://everyayah.com/data/Minshawy_Mujawwad_192kbps';
    const pad3 = (n) => String(n).padStart(3, '0');

    function buildAyahAudioUrls(ref) {
      const urls = [];
      for (let ayah = ref.start; ayah <= ref.end; ayah++) {
        urls.push(`${AYAH_AUDIO_BASE}/${pad3(ref.surahNum)}${pad3(ayah)}.mp3`);
      }
      return urls.slice(0, 4); // لا تتجاوز 4 مقاطع متتابعة لكل آية
    }

    // --- حسّم الصوت الموحد: يمنع تشغيل أكثر من صوتٍ واحد (تلاوة/أذان/تنبيه) في الوقت نفسه ---
    const audioBus = { key: null, element: null, onStolen: {} };

    function claimAudio(key, element) {
      if (key === 'remind' && audioBus.key === 'kahf') return; // تنبيه الربع لا يقطع التلاوة
      if (audioBus.key && audioBus.key !== key) {
        try { audioBus.element.pause(); } catch (e) { /* لا صوت نشط */ }
        const stolen = audioBus.key;
        if (typeof audioBus.onStolen[stolen] === 'function') audioBus.onStolen[stolen]();
      }
      audioBus.key = key;
      audioBus.element = element || null;
    }

    function releaseAudio(key) {
      if (audioBus.key === key) {
        audioBus.key = null;
        audioBus.element = null;
      }
    }

