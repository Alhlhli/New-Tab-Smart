    function resetAyahPlayer() {
      ayahPlaying = false;
      releaseAudio('ayah');
      if (ayahAudioElement) {
        try { ayahAudioElement.pause(); } catch (e) { /* غير مُحمَّل بعد */ }
      }
      setAyahPlayIcon('idle');
    }

    audioBus.onStolen.ayah = resetAyahPlayer;

    function toggleAyahAudio() {
      if (ayahPlaying) {
        resetAyahPlayer();
        return;
      }
      const ref = parseAyahSourceRef((tadabburDatabase[currentAyahIdx] || {}).surah || '');
      if (!ref) {
        showNoticeToast('تعذّر التعرّف على رقم السورة والآية.', 'fa-circle-exclamation', 6000);
        return;
      }
      ayahQueue = buildAyahAudioUrls(ref);
      ayahQueuePos = 0;
      if (!ayahAudioElement) {
        ayahAudioElement = new Audio();
        ayahAudioElement.addEventListener('ended', () => {
          if (!ayahPlaying) return;
          ayahQueuePos += 1;
          if (ayahQueuePos >= ayahQueue.length) {
            resetAyahPlayer();
            showNoticeToast('تمّت قراءة الآية كاملة.', 'fa-book-open-reader', 4000);
          } else {
            playCurrentAyahPart();
          }
        });
        ayahAudioElement.addEventListener('error', () => {
          resetAyahPlayer();
          showNoticeToast('تعذّر تحميل تلاوة الآية، تأكد من الاتصال بالإنترنت.', 'fa-triangle-exclamation', 7000);
        });
      }
      playCurrentAyahPart();
    }

    function playCurrentAyahPart() {
      if (!ayahQueue.length || !ayahAudioElement) {
        resetAyahPlayer();
        return;
      }
      ayahAudioElement.src = ayahQueue[ayahQueuePos];
      ayahAudioElement.volume = 1;
      claimAudio('ayah', ayahAudioElement);
      ayahPlaying = true;
      setAyahPlayIcon('playing');
      ayahAudioElement.play().catch(() => {
        resetAyahPlayer();
        showNoticeToast('منع المتصفح التشغيل الأول، انقر زر التلاوة مرة أخرى.', 'fa-hand-pointer', 7000);
      });
    }

