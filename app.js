    // سحب المقبض العلوي يمدّ القائمة لأعلى الشاشة بحرية
    function setupTasksResize() {
      const popover = $('tasksPopover');
      const handle = $('tasksResizeHandle');
      if (!popover || !handle) return;

      let startY = 0;
      let startHeight = 0;
      let dragging = false;
      const MIN_HEIGHT = 220;

      // أقصى ارتفاع ممكن دون تجاوز أعلى الشاشة، مبني على ارتفاع الشريط السفلي
      const maxHeight = () => {
        const footerVar = parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--footer-h'));
        const reserve = Number.isFinite(footerVar) ? footerVar + 20 : 94;
        return Math.max(MIN_HEIGHT, window.innerHeight - reserve);
      };

      const applyHeight = (height) => {
        const value = Math.max(MIN_HEIGHT, Math.min(maxHeight(), height));
        popover.style.height = `${value}px`;
        popover.style.maxHeight = `${value}px`;
      };

      handle.addEventListener('pointerdown', (event) => {
        dragging = true;
        startY = event.clientY;
        startHeight = popover.getBoundingClientRect().height;
        popover.style.height = `${startHeight}px`;
        popover.style.maxHeight = `${startHeight}px`;
        popover.classList.remove('is-expanded');
        popover.classList.add('is-resized');
        try { handle.setPointerCapture(event.pointerId); } catch (e) { /* ignore */ }
        document.body.style.cursor = 'ns-resize';
        event.preventDefault();
      });

      handle.addEventListener('pointermove', (event) => {
        if (!dragging) return;
        applyHeight(startHeight + (startY - event.clientY));
      });

      const stopDragging = (event) => {
        if (!dragging) return;
        dragging = false;
        document.body.style.cursor = '';
        try { handle.releasePointerCapture(event.pointerId); } catch (e) { /* ignore */ }
        store.set('tv_tasks_height', String(Math.round(popover.getBoundingClientRect().height)));
        store.set('tv_tasks_expanded', '0');
      };

      handle.addEventListener('pointerup', stopDragging);
      handle.addEventListener('pointercancel', stopDragging);

      window.addEventListener('resize', () => {
        if (popover.classList.contains('is-expanded') || !popover.style.height) return;
        applyHeight(popover.getBoundingClientRect().height);
      });
    }

