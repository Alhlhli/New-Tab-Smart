    // Measures the normal responsive layout. Hidden cards are measured too so their
    // saved spots are ready when the user shows them again.
    function captureResponsiveLayout() {
      const dash = layoutDashboard();
      if (!dash) return null;

      dash.classList.remove('custom-layout');
      clearLayoutInlineGeometry();
      dash.scrollTop = 0;

      const hidden = [];
      LAYOUT_WIDGETS.forEach(({ id }) => {
        const el = $(id);
        if (el && el.classList.contains('widget-hidden')) {
          hidden.push(el);
          el.classList.remove('widget-hidden');
        }
      });

      const width = dash.clientWidth || 1;
      const origin = dash.getBoundingClientRect();
      const widgets = {};
      const base = {};
      const scale = {};

      LAYOUT_WIDGETS.forEach(({ id }) => {
        const el = $(id);
        if (!el) return;
        const rect = el.getBoundingClientRect();
        const normalized = {
          x: (rect.left - origin.left) / width,
          y: (rect.top - origin.top) / width, // نفس مقياس العرض لتبقى النسب ثابتة عند تغيير المقاس
          w: rect.width / width,
          h: rect.height / width
        };
        widgets[id] = normalized;
        base[id] = { ...normalized };
        scale[id] = 100;
      });

      hidden.forEach((el) => el.classList.add('widget-hidden'));

      layoutData = { v: 1, widgets, base, scale };
      saveLayoutData();
      syncScaleControls();
      return layoutData;
    }

